// Compiles content/ into the app bundle (ios/SystemDesignTrainer/Resources/content/*.json)
// and validates it.
//   node scripts/build-content.mjs            build, fail on validation errors
//   node scripts/build-content.mjs --strict   also enforce the delivery targets
//   node scripts/build-content.mjs --report   also rewrite docs/COVERAGE.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { compileContent, checkTargets, SKILLS, FORMATS } from './content-lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const C = path.join(root, 'content');
const OUT = path.join(root, 'ios', 'SystemDesignTrainer', 'Resources', 'content');
const args = new Set(process.argv.slice(2));

const readDir = (dir, ext) => {
  const abs = path.join(C, dir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs, { recursive: true })
    .map(String)
    .filter((f) => f.endsWith(ext))
    .sort()
    .map((f) => ({ path: path.join('content', dir, f), text: fs.readFileSync(path.join(abs, f), 'utf8') }));
};
const readYaml = (f, fallback) => (fs.existsSync(path.join(C, f)) ? yaml.load(fs.readFileSync(path.join(C, f), 'utf8')) : fallback);

const raw = {
  modules: readYaml('modules.yaml', []),
  // every content/sources/*.yaml is merged into one registry; duplicate keys are an error
  sources: readDir('sources', '.yaml').reduce((acc, f) => {
    for (const [k, v] of Object.entries(yaml.load(f.text) ?? {})) {
      if (acc[k]) throw new Error(`${f.path}: source key "${k}" is already defined`);
      if (!v?.title || !/^https?:\/\//.test(v?.url ?? '')) throw new Error(`${f.path}: source "${k}" needs title and url`);
      acc[k] = v;
    }
    return acc;
  }, {}),
  lessons: readDir('lessons', '.md'),
  cases: readDir('cases', '.md'),
  labs: readDir('labs', '.md'),
  itemFiles: readDir('items', '.yaml'),
};

const { errors, warnings, data, stats } = compileContent(raw);
for (const w of warnings) console.warn('warning:', w);
if (args.has('--strict')) errors.push(...checkTargets(stats).map((m) => `target not met: ${m}`));
if (errors.length) {
  console.error(`\n${errors.length} content error(s):`);
  for (const e of errors) console.error('  - ' + e);
  process.exit(1);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const write = (name, obj) => fs.writeFileSync(path.join(OUT, name), JSON.stringify(obj));

const itemMeta = data.items.map(({ id, concepts, pool, skill, format, difficulty, lessonId, caseId }) => ({ id, concepts, pool, skill, format, difficulty, lessonId, caseId }));
write('index.json', {
  stats,
  modules: data.modules,
  lessons: data.lessons,
  concepts: data.concepts,
  items: itemMeta,
  cases: data.cases,
  labs: data.labs,
});
write('items.json', Object.fromEntries(data.items.map((i) => [i.id, i])));
write('lessons.json', data.lessonBodies);
write('cases.json', data.caseBodies);
write('labs.json', data.labBodies);

console.log(
  `content ok: ${stats.lessons} lessons, ${stats.concepts} concepts, ${stats.items} items ` +
    `(${stats.practiceItems} practice / ${stats.assessItems} assess / ${stats.finalItems} final), ` +
    `${stats.cases} cases, ${stats.labs} labs, ~${stats.words} words`,
);

if (args.has('--report')) {
  const L = [];
  L.push('# Coverage report', '', '_Generated by `npm run content -- --report`. Do not edit by hand._', '');
  L.push(`- Lessons: **${stats.lessons}** · Concepts: **${stats.concepts}** · Case studies: **${stats.cases}** · Labs: **${stats.labs}**`);
  L.push(`- Items: **${stats.items}** (practice ${stats.practiceItems}, assessment ${stats.assessItems}, final ${stats.finalItems})`);
  L.push(`- By format: ${FORMATS.map((f) => `${f} ${stats.byFormat[f]}`).join(', ')}`);
  L.push(`- By skill: ${SKILLS.map((s) => `${s} ${stats.bySkill[s]}`).join(', ')}`);
  L.push(`- Lesson and case-study text: about ${stats.words.toLocaleString('en-US')} words`, '');
  for (const m of data.modules) {
    L.push(`## ${m.title}`, '', '| # | Lesson | Prerequisites | Objective | Concepts | Practice / Assess | Sources |', '|---|---|---|---|---|---|---|');
    for (const l of data.lessons.filter((x) => x.module === m.id)) {
      const its = data.items.filter((i) => i.lessonId === l.id);
      const src = data.lessonBodies[l.id].sources.map((s) => `${s.title}: ${s.section}`).join('; ');
      const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
      L.push(
        `| ${l.order} | ${cell(l.title)} | ${l.prereqs.map((p) => '`' + p + '`').join(', ') || '—'} | ${cell(l.objective)} | ${l.concepts.map((c) => cell(data.concepts[c].name)).join('; ')} | ${its.filter((i) => i.pool === 'practice').length} / ${its.filter((i) => i.pool === 'assess').length} | ${cell(src)} |`,
      );
    }
    L.push('');
  }
  L.push('## Case studies', '', '| Case | Prerequisite lessons | Concepts exercised |', '|---|---|---|');
  for (const c of data.cases) L.push(`| ${c.title} | ${c.prereqs.length} | ${c.concepts.map((x) => data.concepts[x].name).join('; ')} |`);
  L.push('', '## Labs (need a development environment)', '', '| Lab | Reinforces |', '|---|---|');
  for (const b of data.labs) L.push(`| ${b.title} | ${b.lessons.map((x) => '`' + x + '`').join(', ')} |`);
  L.push('');
  fs.writeFileSync(path.join(root, 'docs', 'COVERAGE.md'), L.join('\n'));
  console.log('wrote docs/COVERAGE.md');
}
